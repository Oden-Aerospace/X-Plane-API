"""Low-level Mode S Extended Squitter frame construction and serialization."""

from __future__ import annotations

from dataclasses import dataclass

_FRAME_BITS = 112
_DATA_BITS = 88
_PARITY_BITS = 24
_GENERATOR = 0x1FFF409


def mode_s_crc(data_88_bits: int) -> int:
    """Return the 24-bit Mode S CRC remainder for an 88-bit message prefix."""
    if isinstance(data_88_bits, bool) or not isinstance(data_88_bits, int):
        raise TypeError("data_88_bits must be an integer")
    if not 0 <= data_88_bits < (1 << _DATA_BITS):
        raise ValueError("data_88_bits must fit in 88 bits")

    remainder = data_88_bits << _PARITY_BITS
    for bit_index in range(_FRAME_BITS - 1, _PARITY_BITS - 1, -1):
        if remainder & (1 << bit_index):
            remainder ^= _GENERATOR << (bit_index - _PARITY_BITS)
    return remainder & ((1 << _PARITY_BITS) - 1)


def validate_icao_address(address: str | int) -> int:
    """Validate and parse an explicitly configured 24-bit ICAO address.

    Strings may contain exactly six hexadecimal characters, optionally prefixed
    by ``0x``. Integer zero is permitted only as an explicit test value; no
    value is ever generated by this helper.
    """
    if isinstance(address, bool):
        raise ValueError("ICAO address must be a 24-bit integer or six hex digits")
    if isinstance(address, int):
        value = address
    elif isinstance(address, str):
        encoded = address[2:] if address.lower().startswith("0x") else address
        if len(encoded) != 6:
            raise ValueError("ICAO address text must contain exactly six hex digits")
        try:
            value = int(encoded, 16)
        except ValueError as exc:
            raise ValueError("ICAO address must be hexadecimal") from exc
    else:
        raise TypeError("ICAO address must be an integer or string")
    if not 0 <= value <= 0xFFFFFF:
        raise ValueError("ICAO address must fit in 24 bits")
    return value


@dataclass(frozen=True, slots=True)
class ModeSFrame:
    """A complete 112-bit Mode S frame with computed CRC parity."""

    data_88_bits: int

    def __post_init__(self) -> None:
        if isinstance(self.data_88_bits, bool) or not isinstance(self.data_88_bits, int):
            raise TypeError("data_88_bits must be an integer")
        if not 0 <= self.data_88_bits < (1 << _DATA_BITS):
            raise ValueError("data_88_bits must fit in 88 bits")

    @property
    def value(self) -> int:
        return (self.data_88_bits << _PARITY_BITS) | mode_s_crc(self.data_88_bits)

    @property
    def raw(self) -> bytes:
        return self.value.to_bytes(_FRAME_BITS // 8, "big")

    @property
    def hex(self) -> str:
        return self.raw.hex().upper()

    @property
    def avr(self) -> str:
        """Dump1090-style AVR text framing for one long Mode S frame."""
        return f"*{self.hex};"


def build_df17_frame(
    *,
    icao_address: str | int,
    me_payload: int,
    capability: int,
) -> ModeSFrame:
    """Build a DF17 frame prefix; callers supply all semantic ME payload bits."""
    address = validate_icao_address(icao_address)
    if isinstance(me_payload, bool) or not isinstance(me_payload, int):
        raise TypeError("me_payload must be an integer")
    if not 0 <= me_payload < (1 << 56):
        raise ValueError("me_payload must fit in 56 bits")
    if isinstance(capability, bool) or not isinstance(capability, int):
        raise TypeError("capability must be an integer")
    if not 0 <= capability <= 7:
        raise ValueError("capability must be in the range 0..7")

    downlink_format = 17
    data_prefix = (downlink_format << 83) | (capability << 80) | (address << 56) | me_payload
    return ModeSFrame(data_prefix)


__all__ = ["ModeSFrame", "build_df17_frame", "mode_s_crc", "validate_icao_address"]
